function breadcrumb(ctx, items, r) {
  const { s } = ctx;
  const li = [`<li><a href="${r}index.html">${esc(s.home)}</a></li>`].concat(items.map(([label, href]) =>
    href ? `<li><a href="${r}${href}">${esc(label)}</a></li>` : `<li aria-current="page">${esc(label)}</li>`));
  return `<nav class="breadcrumb" aria-label="Breadcrumb"><ol>${li.join('')}</ol></nav>`;
}

function picture(img, r, alt, { sizes = '100vw', eager = false } = {}) {
  const srcset = img.srcset.split(',').map((p) => r + p.trim()).join(', ');
  const src = r + (img.fallback || img.src);
  return `<picture><source type="image/webp" srcset="${srcset}" sizes="${sizes}"><img src="${src}" width="${img.width}" height="${img.height}" alt="${attr(alt)}"${eager ? ' fetchpriority="high"' : ' loading="lazy"'} decoding="async"></picture>`;
}

