function partialPages(ctx) {
  const dir = join(ROOT, 'src/pages');
  return readdirSync(dir).filter((f) => f.endsWith('.html')).sort().map((f) => {
    const raw = readFileSync(join(dir, f), 'utf8');
    const m = raw.match(/^<!--meta\s*([\s\S]*?)-->\s*/);
    if (!m) throw new Error(`${f}: missing <!--meta … --> block`);
    const meta = JSON.parse(m[1]);
    const depth = meta.path.split('/').length - 1;
    const r = meta.absolute ? site.basePath : '../'.repeat(depth);
    let body = raw.slice(m[0].length);
    body = body.replace('{{breadcrumb}}', meta.breadcrumb ? breadcrumb(ctx, meta.breadcrumb, r) : '');
    body = body.replace(/\{\{icon:([a-z]+)\}\}/g, (_, n) => icon(n));
    body = body.replace('{{doc-allowlist}}', () => docAllowlist(ctx));
    return { ...meta, body };
  });
}

function docAllowlist(ctx) {
  const { t } = ctx;
  const docs = {};
  for (const [id, d] of Object.entries(site.documents)) {
    if (!existsSync(join(ROOT, d.file))) throw new Error(`Document ${id} points to a missing file: ${d.file}`);
    docs[id] = { file: d.file, title: t(d.title), back: d.back };
  }
  return `<script type="application/json" id="doc-allowlist">${JSON.stringify(docs).replace(/</g, '\\u003c')}</script>`;
}

// 404: GitHub Pages serves this for any missing path under the site, so it
// uses absolute URLs and redirects old or differently-cased links to the
// canonical page. Only targets from this table are ever used.
function notFoundPage(ctx, allPaths) {
  const legacy = {
    'resources/referances.pdf': 'Resources/References.pdf',
    'resources/fmva.pdf': 'Resources/Certificates/FMVA.pdf',
    'certificates/fmva.pdf': 'Resources/Certificates/FMVA.pdf',
    'resources/cv.html': 'cv.html'
  };
  for (let n = 1; n <= 5; n++) {
    legacy[`resources/references/recommendation${n}.pdf`] = 'references.html';
    legacy[`resources/recommendations/recommendation${n}.pdf`] = 'references.html';
  }
  const map = { ...legacy };
  for (const p of allPaths) {
    const clean = p.replace(/(^|\/)index\.html$/, '$1');
    map[p.toLowerCase()] = clean;
    map[clean.toLowerCase()] = clean;
    if (clean.endsWith('/')) map[clean.slice(0, -1).toLowerCase()] = clean;
    if (p.endsWith('.html')) map[p.slice(0, -5).toLowerCase()] = clean;
  }
  const body = `<div class="container">
  <header class="page-head">
    <p class="eyebrow">404</p>
    <h1 class="h1">Page not found</h1>
    <p class="lead">The page may have moved. These links cover everything on the site:</p>
  </header>
  <ul class="link-list">
    <li><a href="${site.basePath}"><span class="k">Home</span><span class="v">${esc(ctx.t(site.person.name))}</span>${icon('arrow')}</a></li>
    <li><a href="${site.basePath}projects/"><span class="k">Projects</span><span class="v">All projects</span>${icon('arrow')}</a></li>
    <li><a href="${site.basePath}cv.html"><span class="k">CV</span><span class="v">Curriculum vitae</span>${icon('arrow')}</a></li>
    <li><a href="${site.basePath}certificates.html"><span class="k">Certificates</span><span class="v">Certificates</span>${icon('arrow')}</a></li>
  </ul>
</div>
<script>
(function () {
  var base = ${JSON.stringify(site.basePath)};
  var map = ${JSON.stringify(map)};
  var path = location.pathname;
  if (path.toLowerCase().indexOf(base.toLowerCase()) !== 0) return;
  var rel;
  try { rel = decodeURIComponent(path.slice(base.length)); } catch (e) { return; }
  var key = rel.toLowerCase().replace(/\\/index\\.html$/, '/');
  var target = Object.prototype.hasOwnProperty.call(map, key) ? map[key] : null;
  if (target !== null && base + target !== path) location.replace(base + target + location.search + location.hash);
})();
</script>`;
  return { path: '404.html', absolute: true, title: 'Page not found', noindex: true, body, description: 'Page not found.' };
}

// ---------- run ----------
function build(locale) {
  const t = makeT(locale);
  const s = site.strings[locale];
  if (!s) throw new Error(`No UI strings for locale ${locale}`);
  const ctx = { t, s, locale };
  const slugs = new Set();
  for (const p of data.projects) {
    if (!/^[a-z0-9-]+$/.test(p.slug) || slugs.has(p.slug)) throw new Error(`Bad or duplicate slug: ${p.slug}`);
    slugs.add(p.slug);
    if (!data.statuses[p.status]) throw new Error(`${p.slug}: unknown status ${p.status}`);
    for (const k of ['title', 'type', 'summary', 'features']) t(p[k], `${p.slug}.${k}`);
    for (const src of p.image.srcset.split(',').map((x) => x.trim().split(' ')[0])) {
      if (!existsSync(join(ROOT, src))) console.warn(`warning: ${p.slug} image missing: ${src}`);
    }
  }
  const pages = [homePage(ctx), projectsPage(ctx), ...data.projects.map((p, i) => projectPage(ctx, p, i)), ...partialPages(ctx)];
  const paths = new Set(pages.map((p) => p.path));
  for (const p of data.projects) {
    if (p.links.demo && !paths.has(p.links.demo + 'index.html')) throw new Error(`${p.slug}: demo page ${p.links.demo} is not built from src/pages`);
  }
  const resources = ['Resources/References.pdf', 'Resources/Certificates/FMVA.pdf'];
  pages.push(notFoundPage(ctx, pages.map((p) => p.path).concat(resources)));
  return pages.map((p) => ({ path: p.path, html: layout(ctx, p), noindex: p.noindex }));
}

const out = build(site.defaultLocale);
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${out.filter((p) => !p.noindex).map((p) => `  <url><loc>${site.siteUrl}${p.path.replace(/(^|\/)index\.html$/, '$1')}</loc></url>`).join('\n')}
</urlset>
`;
out.push({ path: 'sitemap.xml', html: sitemap });

let stale = 0;
for (const { path, html } of out) {
  const file = join(ROOT, path);
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (CHECK) {
    if (current !== html) { console.error(`out of date: ${path}`); stale++; }
    continue;
  }
  if (current !== html) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, html);
    console.log(`wrote ${relative(ROOT, file)}`);
  }
}
if (CHECK) {
  if (stale) { console.error(`${stale} generated file(s) out of date — run node tools/build.mjs`); process.exit(1); }
  console.log(`all ${out.length} generated files up to date`);
}
