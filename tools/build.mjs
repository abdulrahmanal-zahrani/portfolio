// ---------- i18n ----------
// Every visible string is a { locale: text } object. A missing translation is
// a build error rather than a silent fallback to another language.
function makeT(locale) {
  return (v, where = '') => {
    if (v == null) return v;
    if (typeof v === 'string' || Array.isArray(v)) return v;
    if (!(locale in v)) throw new Error(`Missing "${locale}" text ${where}: ${JSON.stringify(v).slice(0, 80)}`);
    return v[locale];
  };
}

